// GET /:id - single agent detail
agentsRouter.get('/:id', (c) => {
  const id = c.req.param('id');
  const db = getDb();
  const row = db.prepare('SELECT * FROM agents WHERE id = ?').get(id) as Record<string, unknown> | undefined;

  if (!row) {
    return c.json({ ok: false, error: 'Agent not found' }, 404);
  }

  const agent = rowToAgentDetail(row);
  // ── THE EFFECTIVE SCOPE, READABLE ANY TIME (PHASE-5 T5 Step 2) ──
  // `permissions` is the STORED blob and it is not the answer to "what can this
  // agent actually do": it is `'{}'` for 40 of 56 agents on the dev body, it is
  // partial for others, and the platform's own identity rules override it for
  // the primary. `effectiveScope` is what `getAgentPermissions` actually returns
  // — defaults filled in, identity applied, the agent's own artifact directory
  // present — so nobody has to reconstruct it from three files to answer the
  // question. Additive: `permissions` still carries the stored blob byte for
  // byte, because a reader that wants to know what was WRITTEN still can.
  return c.json({ ok: true, data: { ...agent, effectiveScope: getAgentPermissions(id) } });
});

// PATCH /:id/model - set agent's model
agentsRouter.patch('/:id/model', async (c) => {
  const id = c.req.param('id');
  const db = getDb();

  const agent = db.prepare('SELECT id FROM agents WHERE id = ?').get(id);
  if (!agent) {
    return c.json({ ok: false, error: 'Agent not found' }, 404);
  }

  const body = await c.req.json().catch(() => null);
  if (!body || typeof body.modelId !== 'string') {
    return c.json({ ok: false, error: 'modelId string is required' }, 400);
  }

  const { modelId } = body;

  if (modelId === 'auto') {
    db.prepare("UPDATE agents SET model_id = 'auto', updated_at = datetime('now') WHERE id = ?").run(id);
    logger.info('Agent model set to auto-router', { agentId: id });
  } else {
    const model = db.prepare('SELECT id, name FROM models WHERE id = ? AND is_enabled = 1').get(modelId) as { id: string; name: string } | undefined;
    if (!model) {
      return c.json({ ok: false, error: 'Model not found or not enabled' }, 400);
    }
    db.prepare("UPDATE agents SET model_id = ?, updated_at = datetime('now') WHERE id = ?").run(modelId, id);
    logger.info('Agent model updated', { agentId: id, modelId, modelName: model.name });
  }

  // Sanitize tool call messages so the new model doesn't choke on
  // tool_use IDs generated by the previous model
  sanitizeMessagesOnModelChange(id);

  // Keep config-table model keys in sync for persistent agents whose runtime
  // reads from config rather than agents.model_id directly.
  const upsert = db.prepare(`
    INSERT INTO config (key, value, updated_at) VALUES (?, ?, datetime('now'))
    ON CONFLICT(key) DO UPDATE SET value = excluded.value, updated_at = excluded.updated_at
  `);
  if (id === getHealerAgentId()) {
    upsert.run('healer_model_id', modelId);
    logger.info('Synced healer_model_id config key', { modelId });
  } else if (id === getDreamerAgentId()) {
    upsert.run('dreaming_model_id', modelId);
    logger.info('Synced dreaming_model_id config key', { modelId });
  } else if (id === getImaginerAgentId()) {
    upsert.run('imaginer_image_model', modelId);
    logger.info('Synced imaginer_image_model config key', { modelId });
  }

  // Return updated agent
  const row = db.prepare('SELECT * FROM agents WHERE id = ?').get(id) as Record<string, unknown>;
  return c.json({ ok: true, data: rowToAgentDetail(row) });
});

// POST / — create standalone agent from dashboard
agentsRouter.post('/', async (c) => {
  const body = await c.req.json().catch(() => null);

  if (!body || typeof body.name !== 'string' || typeof body.systemPrompt !== 'string') {
    return c.json({ ok: false, error: 'name (string) and systemPrompt (string) are required' }, 400);
  }

  try {
    const db = getDb();
    const agentId = uuidv4();

    // ── THE SAME VALIDATION PATH THE SPAWNER USES (PHASE-5 T5 Step 2) ──
    // This route used to write `JSON.stringify(body.permissions ?? {})` straight
    // into the row: no schema, no bound, no reader. A manifest of the wrong shape
    // was stored happily and silently downgraded to the default by the next
    // reader, and a manifest claiming more than the platform grants was stored
    // just as happily. The plan's requirement is that dashboard agent creation
    // goes through the SAME path, so it does — literally the same function.
    //
    // The parent here is the PRIMARY agent's scope, because that is what a
    // dashboard-created agent is bounded by: the route is the owner acting, and
    // the owner's own agent is the ceiling. A body that names no manifest gets
    // the decided default, exactly as a spawn does.
    const scope = resolveChildScope(
      body.permissions,
      getAgentPermissions(getPrimaryAgentId()),
      agentId,
    );
    if (!scope.ok) {
      // A REFUSAL, NOT A DOWNGRADE. 400 rather than 500: the caller sent
      // something the platform will not store, and the message names the field.
      logger.warn('Dashboard agent creation refused an invalid manifest', { reason: scope.reason });
      return c.json({ ok: false, error: `Agent not created — ${scope.reason}` }, 400);
    }

    const resolvedModelId = body.modelId || null;
    const config = JSON.stringify({
      shareUserProfile: body.shareUserProfile || undefined,
    });
    const timeoutSeconds = body.timeout ? Number(body.timeout) : null;
    const timeoutAt = timeoutSeconds ? new Date(Date.now() + timeoutSeconds * 1000).toISOString() : null;

    const classification = body.classification === 'ronin' ? 'ronin' : 'apprentice';

    const groupId = body.groupId ?? null;

    // T11 Step 1b: who made this agent. This route is the dashboard create form, so a
    // person made it — unless the caller DECLARES otherwise, which is how the behavioral
    // harness stamps its BehaviorBot and its five fixture peers as disposable. An
    // unrecognised value falls back to 'user' (parseCreatedByKind returns null), so a
    // typo can only ever NARROW what a sweep may touch, never widen it.
    const createdByKind = parseCreatedByKind(body.createdByKind) ?? 'user';

    db.prepare(`
      INSERT INTO agents (id, name, model_id, system_prompt_path, status, config, created_by, created_by_kind,
                          parent_agent, spawn_depth, agent_type, classification, group_id, max_runtime, timeout_at,
                          permissions, tools_policy, equipped_techniques, task_id, created_at, updated_at)
      VALUES (?, ?, ?, NULL, 'idle', ?, 'dashboard', ?,
              NULL, 0, 'standard', ?, ?, ?, ?, ?, ?, ?, ?, datetime('now'), datetime('now'))
    `).run(
      agentId,
      body.name,
      resolvedModelId,
      config,
      createdByKind,
      classification,
      groupId,
      timeoutSeconds,
      timeoutAt,
      JSON.stringify(scope.manifest),
      JSON.stringify(body.toolsPolicy ?? {}),
      JSON.stringify(body.equippedTechniques ?? []),
      body.taskId ?? null,
    );

    // Store system prompt as first message (no spawn injection)
    insertMessageIfAbsent({ id: uuidv4(), agentId, role: 'system', content: body.systemPrompt });

    // FA-PT6: persist the charter durably (migration 096) so getSoulContent
    // reads it directly instead of sniffing the earliest role='system' row.
    try {
      db.prepare('UPDATE agents SET charter = ? WHERE id = ?').run(body.systemPrompt, agentId);
    } catch { /* charter column may not exist on a very old database */ }

    // Store initial user message — just the task, no IMPORTANT INSTRUCTIONS
    const initMsgId = uuidv4();
    insertMessageIfAbsent({ id: initMsgId, agentId, role: 'user', content: body.systemPrompt });
    // T9 (research 17 D4): persisted and never broadcast. It is an owner-lane user row
    // that the chat history route serves, so the agent's first message used to appear
    // only on reload. The agent:created event below tells the dashboard the agent exists;
    // it says nothing about this row.
    broadcast({
      type: 'chat:message',
      agentId,
      message: {
        id: initMsgId, agentId, role: 'user' as const, content: body.systemPrompt,
        tokenCount: null, modelId: null, cost: null, latencyMs: null,
        createdAt: new Date().toISOString(),
      },
    });

    // Start the agent runtime
    const runtime = getAgentRuntime();
    runtime.handleMessage(agentId, body.systemPrompt).catch(err => {
      logger.error('Dashboard agent initial run failed', {
        agentId,
        error: err instanceof Error ? err.message : String(err),
      });
    });

    logger.info('Dashboard agent created', { agentId, name: body.name });

    broadcast({
      type: 'agent:created',
      data: {
        id: agentId,
        name: body.name,
        modelId: resolvedModelId,
        systemPromptPath: null,
        status: 'idle' as const,
        config: JSON.parse(config),
        createdBy: 'dashboard',
        createdAt: new Date().toISOString(),
        updatedAt: new Date().toISOString(),
        parentAgent: null,
        spawnDepth: 0,
        agentType: 'standard' as const,
        classification: classification as 'ronin' | 'apprentice',
        groupId: null,
        maxRuntime: timeoutSeconds,
        timeoutAt,
        permissions: scope.manifest,
        toolsPolicy: body.toolsPolicy ?? {},
        equippedTechniques: body.equippedTechniques ?? [],
        taskId: body.taskId ?? null,
      },
    });

    const row = db.prepare('SELECT * FROM agents WHERE id = ?').get(agentId) as Record<string, unknown>;
    return c.json({ ok: true, data: rowToAgentDetail(row) }, 201);
  } catch (err) {
    const msg = err instanceof Error ? err.message : String(err);
    logger.error('Failed to create agent', { error: msg });
    return c.json({ ok: false, error: msg }, 500);
  }
});

